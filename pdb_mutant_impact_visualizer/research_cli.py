@click.group(context_settings={"help_option_names": ["-h", "--help"]})
@click.version_option(__version__, prog_name="pdbmi")
def cli() -> None:
    """PDB Mutant Impact Visualizer: reproducible DAG pipeline and research tools."""


cli.add_command(run_command)


@cli.command("dag")
@click.option("--write", "write_path", type=click.Path(dir_okay=False, path_type=Path), help="Write docs/pipeline-dag.md from the live registry.")
def dag_command(write_path: Path | None) -> None:
    """Print (or write) the pipeline DAG as Mermaid, generated from the code."""
    from .stages import build_graph

    graph = build_graph()
    body = render_dag_markdown(graph)
    if write_path:
        write_path.parent.mkdir(parents=True, exist_ok=True)
        write_path.write_text(body, encoding="utf-8")
        click.echo(f"Wrote {write_path}")
    else:
        click.echo(body)


def render_dag_markdown(graph: Any) -> str:
    levels = "\n".join(f"{i + 1}. {', '.join(level)}" for i, level in enumerate(graph.levels()))
    return (
        "# Pipeline DAG\n\n"
        "<!-- Generated by `pdbmi dag --write docs/pipeline-dag.md`. Do not edit by hand; "
        "tests/test_cli_research.py fails if this file drifts from the code. -->\n\n"
        "Dashed nodes are optional; red dashed nodes may contact a remote service or external program. "
        "Stages in the same level are independent of each other.\n\n"
        f"```mermaid\n{graph.to_mermaid()}\n```\n\n"
        f"## Execution levels\n\n{levels}\n"
    )


@cli.command("scan")
@click.option("--pdb", "pdb_id", required=True)
@click.option("--chain", required=True)
@click.option("--positions", required=True, help="e.g. 50 or 45-60,70 (author residue numbers).")
@click.option("--esm-model", default=None, help="Add the ESM-2 score to every variant (model loaded once).")
@click.option("--ml-model", "ml_model_path", type=click.Path(exists=True, dir_okay=False, path_type=Path))
@click.option("--out", "out_dir", type=click.Path(file_okay=False, path_type=Path), default=Path("data/results/scan"), show_default=True)
@click.option("--heatmap-metric", default="relative_sasa", show_default=True, help="Column to draw (e.g. esm_llr, ml_ddg, d_hydropathy).")
@click.option("--data-dir", default="data", show_default=True)
def scan_command(pdb_id: str, chain: str, positions: str, esm_model: str | None, ml_model_path: Path | None,
                 out_dir: Path, heatmap_metric: str, data_dir: str) -> None:
    """Saturation scan: all 19 substitutions at each position, offline by default."""
    from .fetch_structure import download_pdb, load_structure
    from .local_structure import THREE_TO_ONE, get_residue

    try:
        base = RunConfig(chain=chain, mutation="A1V", pdb_id=pdb_id, esm_model=esm_model,
                         ml_model_path=str(ml_model_path) if ml_model_path else None, output_root=data_dir)
        structure = load_structure(download_pdb(pdb_id, Path(data_dir) / "structures"), pdb_id.upper())
        wt = lambda pos: THREE_TO_ONE[get_residue(structure, chain, pos).resname.upper()]  # noqa: E731
        extra: dict[str, Any] | None = None
        if esm_model:
            from .esm_backend import HuggingFaceESM

            shared = HuggingFaceESM(esm_model)
            extra = {"esm_factory": lambda _name: shared}
        rows = research.saturation_scan(base, research.parse_positions(positions), wt, extra_context=extra, progress=click.echo)
    except (ValueError, RuntimeError, KeyError) as exc:
        raise click.ClickException(str(exc)) from exc
    csv_path = research.write_csv(rows, out_dir / f"{pdb_id.upper()}_{chain}_scan.csv", research.SCAN_COLUMNS)
    click.echo(f"Scan table: {csv_path}  ({sum(1 for r in rows if r['error'])} failed variants)")
    try:
        click.echo(f"Heatmap: {research.scan_heatmap(rows, heatmap_metric, out_dir / f'{pdb_id.upper()}_{chain}_{heatmap_metric}.png')}")
    except ImportError:
        click.echo("matplotlib not installed; skipped heatmap (pip install 'pdb-mutant-impact-visualizer[plots]').")


@cli.command("features")
@click.option("--input", "input_path", required=True, type=click.Path(exists=True, dir_okay=False, path_type=Path), help="CSV: pdb_id, chain, mutation[, ddg, group].")
@click.option("--out", "out_path", required=True, type=click.Path(dir_okay=False, path_type=Path))
@click.option("--esm-model", default=None)
@click.option("--data-dir", default="data", show_default=True)
def features_command(input_path: Path, out_path: Path, esm_model: str | None, data_dir: str) -> None:
    """Run the offline pipeline over a mutation table and write a feature table."""
    try:
        rows = research.read_mutation_table(input_path)
    except ValueError as exc:
        raise click.ClickException(str(exc)) from exc
    extra: dict[str, Any] | None = None
    if esm_model:
        from .esm_backend import HuggingFaceESM

        shared = HuggingFaceESM(esm_model)
        extra = {"esm_factory": lambda _name: shared}
    good, bad = research.build_feature_rows(rows, base={"esm_model": esm_model, "output_root": data_dir},
                                            extra_context=extra, progress=click.echo)
    research.write_csv(good, out_path, research.FEATURE_TABLE_COLUMNS)
    if bad:
        research.write_csv(bad, out_path.with_suffix(".failures.csv"), ["row", "error"])
    click.echo(f"{len(good)} rows written to {out_path}; {len(bad)} failed" + (f" (see {out_path.with_suffix('.failures.csv')})" if bad else ""))


@cli.command("train")
@click.option("--features", "features_path", required=True, type=click.Path(exists=True, dir_okay=False, path_type=Path))
@click.option("--feature-groups", default="substitution,structure", show_default=True, help="Comma list from: substitution, structure, language_model.")
@click.option("--target-convention", required=True, help='Sign convention of the ddg column, e.g. "positive = destabilising".')
@click.option("--k", default=5, show_default=True, type=click.IntRange(min=2))
@click.option("--alpha", default=1.0, show_default=True, type=click.FloatRange(min=0))
@click.option("--seed", default=0, show_default=True)
@click.option("--bootstrap", default=1000, show_default=True)
@click.option("--out", "out_dir", type=click.Path(file_okay=False, path_type=Path), default=Path("data/results/model"), show_default=True)
def train_command(features_path: Path, feature_groups: str, target_convention: str, k: int, alpha: float,
                  seed: int, bootstrap: int, out_dir: Path) -> None:
    """Train + evaluate a ridge model with protein-grouped CV, ablations and bootstrap CIs."""
    from . import ml

    groups = [g.strip() for g in feature_groups.split(",") if g.strip()]
    table = research.read_feature_table(features_path)
    digest = ml.file_sha256(features_path)
    try:
        model, card = research.train_from_rows(table, groups, k=k, seed=seed, alpha=alpha, n_boot=bootstrap,
                                               target_convention=target_convention, dataset_sha256=digest)
        ablation = research.run_ablation(table, list(research.FEATURE_GROUPS), k=k, seed=seed, alpha=alpha,
                                         n_boot=bootstrap, target_convention=target_convention)
    except ValueError as exc:
        raise click.ClickException(str(exc)) from exc
    out_dir.mkdir(parents=True, exist_ok=True)
    model_path = ml.save_model(model, out_dir / "model.json", card)
    (out_dir / "ablation.json").write_text(json.dumps(ablation, indent=2) + "\n", encoding="utf-8")
    (out_dir / "ablation.md").write_text(research.ablation_markdown(ablation) + "\n", encoding="utf-8")
    cv = card["cross_validation"]
    click.echo(f"Model: {model_path}\nGrouped {k}-fold CV on {card['n_rows']} variants / {card['n_proteins']} proteins")
    click.echo(f"  model         {cv['model']}\n  mean baseline {cv['mean_baseline']}")
    click.echo(f"  Spearman 95% CI (cluster bootstrap): {card['cluster_bootstrap_95ci']['spearman']}")
    click.echo(f"Ablation table: {out_dir / 'ablation.md'}")


@cli.command("reproduce")
@click.argument("report", type=click.Path(exists=True, dir_okay=False, path_type=Path))
@click.option("--structure", type=click.Path(exists=True, dir_okay=False, path_type=Path), help="Needed if the report used a local file.")
def reproduce_command(report: Path, structure: Path | None) -> None:
    """Re-run a saved report's offline analysis and compare its deterministic fields."""
    data = json.loads(report.read_text(encoding="utf-8"))
    try:
        outcome = research.reproduce(data, str(structure) if structure else None)
    except (ValueError, RuntimeError) as exc:
        raise click.ClickException(str(exc)) from exc
    if outcome["remote_backends_skipped"]:
        click.echo("Note: remote backends (DynaMut2/FoldX/EBI) are not re-run; only offline measurements are compared.")
    if outcome["reproduced"]:
        click.echo("REPRODUCED: all deterministic fields match.")
    else:
        click.echo("NOT REPRODUCED:\n  " + "\n  ".join(outcome["differences"]))
        raise SystemExit(1)


@cli.command("validate")
@click.argument("report", type=click.Path(exists=True, dir_okay=False, path_type=Path))
def validate_command(report: Path) -> None:
    """Check that a JSON report is structurally valid (schema 2.0)."""
    problems = validate_report(json.loads(report.read_text(encoding="utf-8")))
    if problems:
        raise click.ClickException("Invalid report:\n  " + "\n  ".join(problems))
    click.echo("Report is structurally valid.")


